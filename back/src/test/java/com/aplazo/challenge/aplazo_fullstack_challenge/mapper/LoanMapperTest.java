    @Test
    @DisplayName("Should map LoanEntity to LoanResponse correctly")
    void shouldMapLoanEntityToLoanResponseCorrectly() {
        // Given
        UUID loanId = UUID.randomUUID();
        UUID customerId = UUID.randomUUID();
        LocalDateTime createdAt = LocalDateTime.now();

        CustomerEntity customer = CustomerEntity.builder()
                .id(customerId)
                .firstName("Test")
                .lastName("Customer")
                .secondLastName("User")
                .dateOfBirth(LocalDate.of(1990, 1, 1))
                .creditLineAmount(new BigDecimal("1000.00"))
                .availableCreditLineAmount(new BigDecimal("500.00"))
                .createdAt(Instant.now())
                .build();

        List<InstallmentEntity> installments = createTestInstallments(loanId);

        LoanEntity entity = LoanEntity.builder()
                .id(loanId)
                .customer(customer)
                .amount(new BigDecimal("500.00"))
                .status(LoanStatus.ACTIVE)
                .commissionAmount(new BigDecimal("25.00"))
                .createdAt(createdAt)
                .installments(installments)
                .build();

        // When
        LoanResponse response = loanMapper.toResponse(entity);

        // Then
        assertThat(response).isNotNull();
        assertThat(response.getId()).isEqualTo(loanId);
        assertThat(response.getCustomerId()).isEqualTo(customerId);
        assertThat(response.getAmount()).isEqualTo(new BigDecimal("500.00"));
        assertThat(response.getStatus()).isEqualTo(LoanStatus.ACTIVE);
        assertThat(response.getCreatedAt()).isEqualTo(createdAt);

        // Verify payment plan
        assertThat(response.getPaymentPlan()).isNotNull();
        assertThat(response.getPaymentPlan().getCommissionAmount()).isEqualTo(new BigDecimal("25.00"));
        assertThat(response.getPaymentPlan().getInstallments()).hasSize(5);

        // Verify first installment
        assertThat(response.getPaymentPlan().getInstallments().get(0).getStatus()).isEqualTo(InstallmentStatus.NEXT);
        assertThat(response.getPaymentPlan().getInstallments().get(0).getAmount()).isEqualTo(new BigDecimal("105.00"));

        // Verify remaining installments
        for (int i = 1; i < 5; i++) {
            assertThat(response.getPaymentPlan().getInstallments().get(i).getStatus())
                    .isEqualTo(InstallmentStatus.PENDING);
            assertThat(response.getPaymentPlan().getInstallments().get(i).getAmount())
                    .isEqualTo(new BigDecimal("105.00"));
        }
    }

