    @Test
    @DisplayName("Should map installment scheduled payment dates correctly")
    void shouldMapInstallmentScheduledPaymentDatesCorrectly() {
        // Given
        UUID loanId = UUID.randomUUID();
        UUID customerId = UUID.randomUUID();

        CustomerEntity customer = createTestCustomer(customerId);

        LocalDate today = LocalDate.now();
        List<InstallmentEntity> installments = new ArrayList<>();

        // Create a loan entity for the installments to reference
        LoanEntity loanEntity = LoanEntity.builder()
                .id(loanId)
                .amount(new BigDecimal("500.00"))
                .status(LoanStatus.ACTIVE)
                .commissionAmount(new BigDecimal("25.00"))
                .createdAt(LocalDateTime.now())
                .build();

        for (int i = 0; i < 5; i++) {
            InstallmentEntity installment = InstallmentEntity.builder()
                    .id(UUID.randomUUID())
                    .loan(loanEntity) // Set the loan relationship
                    .amount(new BigDecimal("105.00"))
                    .scheduledPaymentDate(today.plusWeeks(2L * (i + 1)))
                    .status(i == 0 ? InstallmentStatus.NEXT : InstallmentStatus.PENDING)
                    .build();
            installments.add(installment);
        }

        LoanEntity entity = LoanEntity.builder()
                .id(loanId)
                .customer(customer)
                .amount(new BigDecimal("500.00"))
                .status(LoanStatus.ACTIVE)
                .commissionAmount(new BigDecimal("25.00"))
                .createdAt(LocalDateTime.now())
                .installments(installments)
                .build();

        // When
        LoanResponse response = loanMapper.toResponse(entity);

        // Then
        assertThat(response.getPaymentPlan().getInstallments()).hasSize(5);

        for (int i = 0; i < 5; i++) {
            LocalDate expectedDate = today.plusWeeks(2L * (i + 1));
            assertThat(response.getPaymentPlan().getInstallments().get(i).getScheduledPaymentDate())
                    .isEqualTo(expectedDate);
        }
    }

